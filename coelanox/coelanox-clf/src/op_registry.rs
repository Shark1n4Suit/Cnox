//! Canonical op_id registry (matches public CLF spec). Maps IR op names to op_id for packager.

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum OpType {
    Unknown,
    Add,
    Subtract,
    Multiply,
    Divide,
    Relu,
    Sigmoid,
    Tanh,
    Softmax,
    LogSoftmax,
    Gelu,
    Swish,
    Sqrt,
    Pow,
    Cos,
    Sin,
    Exp,
    Log,
    Convolution,
    MaxPool,
    AvgPool,
    GlobalMaxPool,
    GlobalAvgPool,
    BatchNorm,
    LayerNorm,
    Dropout,
    Reshape,
    Transpose,
    Permute,
    Concatenate,
    Split,
    Slice,
    Gather,
    Scatter,
    MatMul,
    Gemm,
    ReduceSum,
    ReduceMean,
    ReduceMax,
    ReduceMin,
    ReduceProd,
    Broadcast,
    Expand,
    Equal,
    NotEqual,
    Greater,
    GreaterEqual,
    Less,
    LessEqual,
    And,
    Or,
    Not,
    Min,
    Max,
    Custom(u32),
}

#[must_use]
pub fn op_type_to_clf_id(op_type: OpType) -> u32 {
    match op_type {
        OpType::Unknown | OpType::Custom(0) => 0,
        OpType::Custom(id) => id,
        OpType::Add => 1,
        OpType::Subtract => 2,
        OpType::Multiply => 3,
        OpType::Divide => 4,
        OpType::Relu => 10,
        OpType::Sigmoid => 11,
        OpType::Tanh => 12,
        OpType::Softmax => 13,
        OpType::LogSoftmax => 14,
        OpType::Gelu => 15,
        OpType::Swish => 16,
        OpType::Sqrt => 20,
        OpType::Pow => 21,
        OpType::Cos => 22,
        OpType::Sin => 23,
        OpType::Exp => 24,
        OpType::Log => 25,
        OpType::Convolution => 30,
        OpType::MaxPool => 31,
        OpType::AvgPool => 32,
        OpType::GlobalMaxPool => 33,
        OpType::GlobalAvgPool => 34,
        OpType::BatchNorm => 35,
        OpType::LayerNorm => 36,
        OpType::Dropout => 37,
        OpType::Reshape => 40,
        OpType::Transpose => 41,
        OpType::Permute => 42,
        OpType::Concatenate => 43,
        OpType::Split => 44,
        OpType::Slice => 45,
        OpType::Gather => 46,
        OpType::Scatter => 47,
        OpType::MatMul => 50,
        OpType::Gemm => 51,
        OpType::ReduceSum => 60,
        OpType::ReduceMean => 61,
        OpType::ReduceMax => 62,
        OpType::ReduceMin => 63,
        OpType::ReduceProd => 64,
        OpType::Broadcast => 70,
        OpType::Expand => 71,
        OpType::Equal => 80,
        OpType::NotEqual => 81,
        OpType::Greater => 82,
        OpType::GreaterEqual => 83,
        OpType::Less => 84,
        OpType::LessEqual => 85,
        OpType::And => 90,
        OpType::Or => 91,
        OpType::Not => 92,
        OpType::Min => 93,
        OpType::Max => 94,
    }
}
